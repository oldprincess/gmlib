std::vector<ModeKat> make_mode_kats(const std::vector<std::uint8_t>& key,
                                    const std::vector<std::uint8_t>& plaintext,
                                    const std::vector<std::uint8_t>& ciphertext)
{
    const std::vector<std::uint8_t> zero_block(plaintext.size(), 0);
    return {
        {"known-answer", "ECB", key, {}, plaintext, ciphertext},
        {"known-answer", "CBC", key, zero_block, plaintext, ciphertext},
        {"known-answer", "CFB", key, plaintext, zero_block, ciphertext},
        {"known-answer", "OFB", key, plaintext, zero_block, ciphertext},
        {"known-answer", "CTR", key, plaintext, zero_block, ciphertext},
    };
}

