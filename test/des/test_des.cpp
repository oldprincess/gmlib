#include <cstdint>

#include "test.h"

namespace {

using block_cipher_mode::test::CipherKat;
using block_cipher_mode::test::ModeKat;

const std::vector<CipherKat> KATS = {
    {"zero-key-zero-digit",
     {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
     {0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30, 0x30},
     {0xde, 0x8d, 0x55, 0x14, 0x2b, 0x18, 0xde, 0xb7}},
    {"zero-key-one-digit",
     {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
     {0x31, 0x31, 0x31, 0x31, 0x31, 0x31, 0x31, 0x31},
     {0x23, 0x8d, 0x5a, 0xa6, 0x66, 0x70, 0x6c, 0x3a}},
    {"zero-key-palindrome",
     {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
     {0x31, 0x32, 0x33, 0x34, 0x34, 0x33, 0x32, 0x31},
     {0x96, 0x87, 0x61, 0xd7, 0xa3, 0x92, 0x78, 0x26}},
    {"nonzero-key-palindrome",
     {0x01, 0x23, 0x45, 0x67, 0x76, 0x54, 0x32, 0x10},
     {0x31, 0x32, 0x33, 0x34, 0x34, 0x33, 0x32, 0x31},
     {0x04, 0x70, 0xc5, 0x3d, 0x49, 0x84, 0x7a, 0xbd}},
};

} // namespace

std::vector<CipherKat> get_des_cipher_kats()
{
    return KATS;
}

std::vector<ModeKat> get_des_mode_kats()
{
    std::vector<ModeKat> kats;
    kats.reserve(KATS.size() * 5);
    for (const CipherKat& kat : KATS)
    {
        const std::vector<std::uint8_t> zero_block(kat.plaintext.size(), 0);
        kats.push_back(
            {kat.case_name, "ECB", kat.key, {}, kat.plaintext, kat.ciphertext});
        kats.push_back({kat.case_name, "CBC", kat.key, zero_block,
                        kat.plaintext, kat.ciphertext});
        kats.push_back({kat.case_name, "CFB", kat.key, kat.plaintext,
                        zero_block, kat.ciphertext});
        kats.push_back({kat.case_name, "OFB", kat.key, kat.plaintext,
                        zero_block, kat.ciphertext});
        kats.push_back({kat.case_name, "CTR", kat.key, kat.plaintext,
                        zero_block, kat.ciphertext});
    }
    return kats;
}
