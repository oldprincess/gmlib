static uint8_t tag[16] = {
    0xb5, 0x72, 0x83, 0xb0, 0xbf, 0x10, 0x16, 0x33,
    0xa5, 0x0b, 0x8f, 0x80, 0x1b, 0xcc, 0xec, 0x13,
};

#define PRINT(fmt, ...) \
    printf("[LOG] " fmt " %s:%d\n", ##__VA_ARGS__, __FILE__, __LINE__)

int main()
{
    static uint8_t  buffer[1024 * 1024];
    uint8_t         tag_ptr[16] = {0};
    int             ret;
    EVP_CIPHER*     cipher = NULL;
    EVP_CIPHER_CTX* cctx   = NULL;
    OSSL_PROVIDER*  prov   = NULL;
    OSSL_PARAM      params[5];

    uint8_t* out  = buffer;
    int      outl = 0;

    // set search path
    ret = OSSL_PROVIDER_set_default_search_path(NULL, "./");
    if (!ret)
    {
        PRINT("Failed to set default search path");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }
    prov = OSSL_PROVIDER_load(NULL, LIB_NAME(gmlibprov));
    if (prov == NULL)
    {
        PRINT("OSSL_PROVIDER_load failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    printf("[%d] Provider loaded\n", __LINE__);

    // fetch cipher
    cipher = EVP_CIPHER_fetch(NULL, "SM4-GCM", "provider=gmlibprov");
    if (cipher == NULL)
    {
        PRINT("EVP_CIPHER_fetch failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }
    cctx = EVP_CIPHER_CTX_new();
    if (cctx == NULL)
    {
        PRINT("EVP_CIPHER_CTX_new failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    printf("[%d] EVP Cipher SM4-GCM start\n", __LINE__);

    size_t n  = 16;
    params[0] = OSSL_PARAM_construct_size_t(OSSL_CIPHER_PARAM_IVLEN, &n);
    params[1] = OSSL_PARAM_construct_end();

    ret = EVP_CipherInit_ex2(cctx, cipher, user_key, iv, 1, params);
    if (!ret)
    {
        PRINT("EVP_CipherInit failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    ret = EVP_CipherUpdate(cctx, NULL, &outl, aad, sizeof(aad));
    if (!ret)
    {
        PRINT("EVP_CipherUpdate failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    ret = EVP_CipherUpdate(cctx, out, &outl, pt, sizeof(pt));
    if (!ret)
    {
        PRINT("EVP_CipherUpdate failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }
    out += outl;

    ret = EVP_CipherFinal(cctx, out, &outl);
    if (!ret)
    {
        PRINT("EVP_CipherFinal failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }
    out += outl;

    params[0] = OSSL_PARAM_construct_octet_string(OSSL_CIPHER_PARAM_AEAD_TAG,
                                                  tag_ptr, sizeof(tag_ptr));
    params[1] = OSSL_PARAM_construct_end();
    ret       = EVP_CIPHER_CTX_get_params(cctx, params);

    if ((size_t)out - (size_t)buffer != sizeof(ct))
    {
        PRINT("EVP_CipherFinal failed");
        exit(0);
    }
    if (memcmp(ct, buffer, sizeof(ct)) != 0)
    {
        PRINT("EVP_CipherFinal failed");
        exit(0);
    }
    if (memcmp(tag_ptr, tag, sizeof(tag)) != 0)
    {
        PRINT("EVP_CipherFinal failed");
        exit(0);
    }

    // ==================== DEC =========================

    n         = 16;
    params[0] = OSSL_PARAM_construct_size_t(OSSL_CIPHER_PARAM_AEAD_IVLEN, &n);
    params[1] = OSSL_PARAM_construct_end();

    ret = EVP_CipherInit_ex2(cctx, cipher, user_key, iv, 0, params);
    if (!ret)
    {
        PRINT("EVP_CipherInit failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    outl = 0;
    ret  = EVP_CipherUpdate(cctx, NULL, &outl, aad, sizeof(aad));
    if (!ret)
    {
        PRINT("EVP_CipherUpdate failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    out  = buffer;
    outl = 0;
    ret  = EVP_CipherUpdate(cctx, out, &outl, ct, sizeof(ct));
    if (!ret)
    {
        PRINT("EVP_CipherUpdate failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }
    out += outl;

    params[0] = OSSL_PARAM_construct_octet_string(OSSL_CIPHER_PARAM_AEAD_TAG,
                                                  tag, sizeof(tag));
    params[1] = OSSL_PARAM_construct_end();
    ret       = EVP_CIPHER_CTX_set_params(cctx, params);
    if (!ret)
    {
        PRINT("EVP_CIPHER_CTX_set_params failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }

    ret = EVP_CipherFinal(cctx, out, &outl);
    if (!ret)
    {
        PRINT("EVP_CipherFinal failed");
        PRINT("%s", ERR_error_string(ERR_get_error(), NULL));
        exit(0);
    }
    out += outl;

    if ((size_t)out - (size_t)buffer != sizeof(pt))
    {
        PRINT("EVP_CipherFinal failed");
        exit(0);
    }
    if (memcmp(pt, buffer, sizeof(pt)) != 0)
    {
        PRINT("EVP_CipherFinal failed");
        exit(0);
    }

    EVP_CIPHER_CTX_free(cctx);
    EVP_CIPHER_free(cipher);
    OSSL_PROVIDER_unload(prov);

    printf("[%d] EVP CIPHER SM4-GCM PASS\n", __LINE__);

    return 0;
}